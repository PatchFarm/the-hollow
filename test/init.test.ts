import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { EXIT } from "../src/cli/main.js";
import { copyFixture, runCli, tempProject } from "./helpers.js";

const read = (dir: string, file: string) => readFileSync(path.join(dir, file), "utf8");
const CI = ".github/workflows/ci.yml";

// Keep runs independent of whatever is installed on this machine.
beforeEach(() => {
  process.env.HOLLOW_ACTIONLINT = "/nonexistent/actionlint";
});
afterEach(() => {
  delete process.env.HOLLOW_ACTIONLINT;
});

describe("hollow init", () => {
  it("writes hollow.yml, the CI workflow and Dependabot config", async () => {
    const dir = copyFixture("python-fastapi");
    const result = await runCli(["init", "--yes", "--cwd", dir]);
    expect(result.stderr).toBe("");
    expect(result.code).toBe(EXIT.ok);
    expect(result.stdout).toContain("create         hollow.yml");
    expect(result.stdout).toContain("run `npx the-hollow protect` to protect main");
    expect(result.stdout).toContain("pre-commit install");
    for (const file of [
      ".github/workflows/pr-title.yml",
      ".pre-commit-config.yaml",
      ".editorconfig",
    ]) {
      expect(existsSync(path.join(dir, file))).toBe(true);
    }
    expect(existsSync(path.join(dir, ".github/pull_request_template.md"))).toBe(true);
    expect(existsSync(path.join(dir, ".github/CODEOWNERS"))).toBe(true);
    expect(read(dir, "hollow.yml")).toContain("target: docker");
    expect(read(dir, "hollow.yml")).toContain("yaml-language-server: $schema=");
    expect(read(dir, CI)).toMatch(/^# Generated by The Hollow/);
    expect(existsSync(path.join(dir, ".github/dependabot.yml"))).toBe(true);
  });

  it("asks for the deploy target, offering the detected one", async () => {
    const dir = copyFixture("node-hono-workers");
    const result = await runCli(["init", "--cwd", dir], { answers: [""] });
    expect(result.code).toBe(EXIT.ok);
    expect(result.stdout).toContain("Cloudflare Workers  (suggested)");
    expect(read(dir, "hollow.yml")).toContain("target: cloudflare-workers");
  });

  it("asks for the server when the target is a VPS", async () => {
    const dir = copyFixture("python-django");
    const result = await runCli(["init", "--cwd", dir], {
      answers: ["5", "not a host!", "app.example.com"],
    });
    expect(result.code).toBe(EXIT.ok);
    expect(read(dir, "hollow.yml")).toContain("host: app.example.com");
  });

  it("suggests Vercel for a Next.js app", async () => {
    const dir = copyFixture("node-next-prisma");
    expect((await runCli(["init", "--yes", "--cwd", dir])).code).toBe(EXIT.ok);
    expect(read(dir, "hollow.yml")).toContain("target: vercel");
  });

  it("cannot pick a target on its own when nothing suggests one", async () => {
    const result = await runCli(["init", "--yes", "--cwd", copyFixture("python-django")]);
    expect(result.code).toBe(EXIT.failure);
    expect(result.stderr).toContain("Pass --target");
  });

  it("refuses an unknown --target and a VPS without a terminal", async () => {
    const dir = copyFixture("python-django");
    expect((await runCli(["init", "--target", "heroku", "--cwd", dir])).stderr).toContain(
      "Unknown deploy target",
    );
    expect((await runCli(["init", "--target", "vps", "--cwd", dir])).stderr).toContain(
      "needs the server's hostname",
    );
    expect(existsSync(path.join(dir, "hollow.yml"))).toBe(false);
  });

  it("names the Pages project after package.json", async () => {
    const dir = copyFixture("node-vite-static");
    await runCli(["init", "--target", "cloudflare-pages", "--yes", "--cwd", dir]);
    expect(read(dir, "hollow.yml")).toContain("projectName: fixture-vite-static");
  });

  it("records a default branch other than main", async () => {
    const dir = copyFixture("node-hono-workers");
    mkdirSync(path.join(dir, ".git/refs/remotes/origin"), { recursive: true });
    writeFileSync(
      path.join(dir, ".git/refs/remotes/origin/HEAD"),
      "ref: refs/remotes/origin/trunk\n",
    );
    await runCli(["init", "--yes", "--cwd", dir]);
    expect(read(dir, "hollow.yml")).toContain("defaultBranch: trunk");
    expect(read(dir, CI)).toContain("- trunk");
  });

  it("keeps an existing hollow.yml", async () => {
    const dir = copyFixture("python-fastapi");
    writeFileSync(
      path.join(dir, "hollow.yml"),
      "version: 1\ndeploy:\n  target: vercel\nsecurity:\n  sast: semgrep\n",
    );
    const result = await runCli(["init", "--cwd", dir]);
    expect(result.stdout).toContain("Using the existing hollow.yml");
    expect(read(dir, "hollow.yml")).toContain("target: vercel");
    expect(read(dir, CI)).not.toContain("codeql");
  });

  it("refuses to overwrite a workflow it did not write, and writes nothing", async () => {
    const dir = copyFixture("python-fastapi");
    mkdirSync(path.join(dir, ".github/workflows"), { recursive: true });
    writeFileSync(path.join(dir, CI), "name: mine\n");
    const result = await runCli(["init", "--yes", "--cwd", dir]);
    expect(result.code).toBe(EXIT.failure);
    expect(result.stderr).toContain(`- ${CI}`);
    expect(read(dir, CI)).toBe("name: mine\n");
    expect(existsSync(path.join(dir, "hollow.yml"))).toBe(false);

    expect((await runCli(["init", "--yes", "--force", "--cwd", dir])).code).toBe(EXIT.ok);
    expect(read(dir, CI)).toMatch(/^# Generated by The Hollow/);
  });

  it("--dry-run writes nothing", async () => {
    const dir = copyFixture("python-fastapi");
    const result = await runCli(["init", "--yes", "--dry-run", "--cwd", dir]);
    expect(result.code).toBe(EXIT.ok);
    expect(result.stdout).toContain(`would create   ${CI}`);
    expect(existsSync(path.join(dir, "hollow.yml"))).toBe(false);
  });

  it("writes nothing when actionlint rejects the workflow", async () => {
    const dir = copyFixture("python-fastapi");
    const bin = path.join(tempProject({}), "actionlint");
    writeFileSync(bin, '#!/bin/sh\necho "ci.yml:1:1: simulated problem"\nexit 1\n');
    chmodSync(bin, 0o755);
    process.env.HOLLOW_ACTIONLINT = bin;
    const result = await runCli(["init", "--yes", "--cwd", dir]);
    expect(result.code).toBe(EXIT.failure);
    expect(result.stderr).toContain("simulated problem");
    expect(existsSync(path.join(dir, CI))).toBe(false);
  });

  it("fails clearly on a project it cannot read", async () => {
    const result = await runCli(["init", "--yes", "--cwd", copyFixture("empty")]);
    expect(result.code).toBe(EXIT.failure);
    expect(result.stderr).toContain("supports Node/TypeScript and Python");
  });

  it("rejects options meant for other commands", async () => {
    expect((await runCli(["upgrade", "--target", "vercel"])).code).toBe(EXIT.usage);
    expect((await runCli(["init", "--json"])).code).toBe(EXIT.usage);
  });
});

describe("files the developer owns", () => {
  it("never overwrites an existing PR template, CODEOWNERS or .editorconfig, even with --force", async () => {
    const dir = copyFixture("python-fastapi");
    mkdirSync(path.join(dir, ".github"), { recursive: true });
    writeFileSync(path.join(dir, ".github/CODEOWNERS"), "* @me\n");
    writeFileSync(path.join(dir, ".editorconfig"), "root = true\n");
    const result = await runCli(["init", "--yes", "--force", "--cwd", dir]);
    expect(result.code).toBe(EXIT.ok);
    expect(result.stdout).toContain("kept           .github/CODEOWNERS  (yours, left as is)");
    expect(read(dir, ".github/CODEOWNERS")).toBe("* @me\n");
    expect(read(dir, ".editorconfig")).toBe("root = true\n");
  });

  it("leaves a pre-commit config it did not write alone, instead of refusing", async () => {
    const dir = copyFixture("python-fastapi");
    writeFileSync(path.join(dir, ".pre-commit-config.yaml"), "repos: []\n");
    const result = await runCli(["init", "--yes", "--cwd", dir]);
    expect(result.code).toBe(EXIT.ok);
    expect(read(dir, ".pre-commit-config.yaml")).toBe("repos: []\n");
  });

  it("adds no pre-commit config when the project uses Husky", async () => {
    const dir = copyFixture("node-hono-workers");
    mkdirSync(path.join(dir, ".husky"));
    const result = await runCli(["init", "--yes", "--cwd", dir]);
    expect(result.stdout).toContain("already uses Husky");
    expect(result.stdout).not.toContain("pre-commit install");
    expect(existsSync(path.join(dir, ".pre-commit-config.yaml"))).toBe(false);
  });

  it("upgrade does not recreate starting-point files the developer deleted", async () => {
    const dir = copyFixture("python-fastapi");
    await runCli(["init", "--yes", "--cwd", dir]);
    rmSync(path.join(dir, ".github/CODEOWNERS"));
    const result = await runCli(["upgrade", "--cwd", dir]);
    expect(result.stdout).not.toContain("CODEOWNERS");
    expect(existsSync(path.join(dir, ".github/CODEOWNERS"))).toBe(false);
  });
});

describe("hollow upgrade", () => {
  it("needs hollow.yml", async () => {
    const result = await runCli(["upgrade", "--cwd", copyFixture("python-fastapi")]);
    expect(result.code).toBe(EXIT.failure);
    expect(result.stderr).toContain("Run `hollow init` first");
  });

  it("regenerates owned files when hollow.yml changes", async () => {
    const dir = copyFixture("python-fastapi");
    await runCli(["init", "--yes", "--cwd", dir]);
    expect((await runCli(["upgrade", "--cwd", dir])).stdout).toContain(`unchanged      ${CI}`);

    writeFileSync(
      path.join(dir, "hollow.yml"),
      "version: 1\ndeploy:\n  target: docker\nsecurity:\n  failOn: critical\n",
    );
    const result = await runCli(["upgrade", "--cwd", dir]);
    expect(result.code).toBe(EXIT.ok);
    expect(result.stdout).toContain(`update         ${CI}`);
    expect(read(dir, CI)).toContain('MIN_CVSS: "9.0"');
  });

  it("overwrites hand edits to generated files, which are marked do-not-edit", async () => {
    const dir = copyFixture("python-fastapi");
    await runCli(["init", "--yes", "--cwd", dir]);
    writeFileSync(path.join(dir, CI), `${read(dir, CI)}\n# hand edit\n`);
    await runCli(["upgrade", "--cwd", dir]);
    expect(read(dir, CI)).not.toContain("hand edit");
  });

  it("reports an invalid hollow.yml", async () => {
    const dir = copyFixture("python-fastapi");
    writeFileSync(path.join(dir, "hollow.yml"), "version: 1\ndeploy:\n  target: nope\n");
    const result = await runCli(["upgrade", "--cwd", dir]);
    expect(result.code).toBe(EXIT.failure);
    expect(result.stderr).toContain("hollow.yml is invalid");
  });
});
