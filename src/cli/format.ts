import type { LoadResult } from "../config/load.js";
import type { Detection, Finding } from "../detect/index.js";
import type { PlanResult } from "../pipeline/plan.js";

/** Human-readable report for `hollow plan`. Plain text, no colors, so it reads well in CI logs. */
export function formatPlan(detection: Detection, config: LoadResult, pipeline: PlanResult): string {
  const lines: string[] = [];
  const row = (label: string, value: string) => lines.push(`  ${label.padEnd(16)} ${value}`);
  const one = <T>(finding: Finding<T> | null) =>
    finding === null ? "not found" : `${String(finding.value)}  (${finding.source})`;
  const many = <T>(findings: Finding<T>[]) =>
    findings.length === 0
      ? "none found"
      : findings.map((finding) => `${String(finding.value)} (${finding.source})`).join(", ");

  lines.push(`Project: ${detection.root}`, "");
  lines.push("Detected");
  row("Language", detection.language === null ? "unknown" : languageLabel(detection));
  row("Package manager", one(detection.packageManager));
  row("Runtime", one(detection.runtimeVersion));
  row("Frameworks", many(detection.frameworks));
  row("Linters", many(detection.quality.linters));
  row("Formatters", many(detection.quality.formatters));
  row("Type checking", many(detection.quality.typeCheckers));
  row("Tests", many(detection.tests.runners));
  row("End-to-end", many(detection.tests.e2e));
  row("Migrations", one(detection.database.migrationTool));
  row("Databases", many(detection.database.engines));
  row(
    "Containers",
    [detection.container.dockerfile, detection.container.compose]
      .filter((file) => file !== null)
      .join(", ") || "none found",
  );
  row("Deploy hints", many(detection.deployHints));

  lines.push("", "hollow.yml");
  switch (config.status) {
    case "missing":
      lines.push("  Not found. `hollow init` creates one.");
      break;
    case "invalid":
      lines.push("  Invalid:");
      for (const error of config.errors) lines.push(`    - ${error}`);
      break;
    case "ok":
      lines.push(`  Valid. Deploy target: ${config.config.deploy.target}.`);
      break;
  }

  if (pipeline.status === "ok") {
    const { plan } = pipeline;
    lines.push("", "CI pipeline (generated by `hollow init` and `hollow upgrade`)");
    row("Install", plan.install.join(" && "));
    for (const check of plan.checks) {
      const label = check.name.replace(/ \(.*\)$/, "");
      row(
        label,
        check.placeholder
          ? "placeholder step that warns on every run (no tests found)"
          : `${check.run}  (${check.reason})`,
      );
    }
    const sast = {
      auto: "CodeQL (public repo) or Semgrep (private repo)",
      codeql: "CodeQL",
      semgrep: "Semgrep",
    }[plan.security.sast];
    const scanners = [
      "Gitleaks",
      "OSV-Scanner",
      sast,
      ...(plan.dockerfile === null ? [] : ["Trivy"]),
    ];
    row("Security", `${scanners.join(", ")}; fails on ${plan.security.failOn} or worse`);
    if (plan.services.length > 0) row("Services", plan.services.map((s) => s.engine).join(", "));
    if (plan.release !== null) {
      const { artifact, releaseType } = plan.release;
      const what =
        artifact.kind === "image"
          ? `container image on GHCR (${artifact.dockerfile}${artifact.starter === null ? "" : ", starter written by init"})`
          : artifact.outputDir === null
            ? "source archive at the tag"
            : `build output archive: ${artifact.outputDir} (${artifact.outputSource})`;
      row("Release", `release-please (${releaseType}); ${what}, with SBOM and provenance`);
    }
    if (plan.deploy !== null) {
      const cloudflare = plan.deploy.cloudflare;
      const where = plan.deploy.vercel
        ? "staged Vercel production deployment, promoted on release; previews for same-repo PRs"
        : cloudflare?.kind === "workers"
          ? "uploaded Worker version (Version URL), deployed to 100% on release"
          : cloudflare?.kind === "pages"
            ? `Pages project ${cloudflare.projectName}: staging branch, then the same build to production; previews for same-repo PRs`
            : plan.deploy.vps === null
              ? "moves the environment's tag on GHCR"
              : `Docker Compose on ${plan.deploy.vps.host} over SSH`;
      const stages = plan.deploy.environments
        .map(
          (environment) =>
            `${environment.name}${environment.onRelease ? " (on release)" : " (every merge)"}`,
        )
        .join(", ");
      row("Deploy", `${stages}; ${where}`);
      const checked = plan.deploy.environments.filter(
        (environment) => environment.healthUrl !== null,
      );
      row(
        "Checks",
        checked.length === 0
          ? "none yet: set environments.<name>.url in hollow.yml to check and roll back each deploy"
          : checked.map((environment) => environment.healthUrl).join(", "),
      );
    }
  } else if (detection.language !== null) {
    lines.push("", "CI pipeline", `  Cannot plan: ${pipeline.error}`);
  }

  const notes = pipeline.status === "ok" ? pipeline.plan.notes : detection.warnings;
  if (notes.length > 0) {
    lines.push("", "Warnings");
    for (const note of notes) lines.push(`  - ${note}`);
  }
  lines.push("");
  return lines.join("\n");
}

function languageLabel(detection: Detection): string {
  if (detection.language === "node") return detection.typescript ? "Node (TypeScript)" : "Node";
  return "Python";
}
