import { Document, isMap, isScalar, visit } from "yaml";
import { pinComments } from "./pins.js";

/** First line of every file The Hollow generates. `upgrade` only overwrites files that start with it. */
export const GENERATED_MARKER = "# Generated by The Hollow";

export interface RenderOptions {
  /** Extra header lines (without `#`) explaining the file. */
  about: string[];
  /** Comments placed above top-level keys or jobs, keyed by `jobs.<id>` or a top-level key. */
  comments?: Record<string, string>;
}

/**
 * Render data as a generated YAML file: header, version comments next to every pin, and a blank
 * line between top-level sections and between jobs so the output reads like hand-written YAML.
 */
export function renderGenerated(data: object, options: RenderOptions): string {
  const doc = new Document(data);
  const pins = pinComments();
  visit(doc, {
    Scalar(_key, node) {
      if (typeof node.value !== "string") return;
      const version = pins.get(node.value);
      if (version !== undefined) node.comment = ` ${version}`;
    },
  });

  const comments = options.comments ?? {};
  if (isMap(doc.contents)) {
    doc.contents.items.forEach((pair, index) => {
      if (!isScalar(pair.key)) return;
      const name = String(pair.key.value);
      if (index > 0) pair.key.spaceBefore = true;
      if (comments[name] !== undefined) pair.key.commentBefore = ` ${comments[name]}`;
      if (name === "jobs" && isMap(pair.value)) {
        pair.value.items.forEach((job, jobIndex) => {
          if (!isScalar(job.key)) return;
          if (jobIndex > 0) job.key.spaceBefore = true;
          const comment = comments[`jobs.${String(job.key.value)}`];
          if (comment !== undefined) job.key.commentBefore = ` ${comment}`;
        });
      }
    });
  }

  const header = [
    `${GENERATED_MARKER} from hollow.yml. Do not edit by hand:`,
    "change hollow.yml, then run `npx the-hollow upgrade`.",
    ...options.about,
  ];
  return `${header.map((line, i) => (i === 0 ? line : `# ${line}`)).join("\n")}\n\n${doc.toString({ lineWidth: 0, nullStr: "" })}`;
}

/** A GitHub Actions expression, `${{ ... }}`. */
export function expr(expression: string): string {
  return `\${{ ${expression} }}`;
}

/** True when a file was written by The Hollow and can be regenerated. */
export function isGenerated(text: string): boolean {
  return text.startsWith(GENERATED_MARKER);
}
